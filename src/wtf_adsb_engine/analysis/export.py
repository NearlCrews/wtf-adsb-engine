def _text(value, maximum=320):
    if not isinstance(value, str) or not value or len(value) > maximum:
        return _MISSING
    if any(ord(char) < 32 for char in value) or any(char in value for char in "<>\\"):
        return _MISSING
    return value


def _token(value):
    return value if isinstance(value, str) and _TOKEN.fullmatch(value) else _MISSING


def _numeric(value):
    result = number(value)
    return result if result is not None else _MISSING


def _boolean(value):
    return value if isinstance(value, bool) else _MISSING


def _enum(*values):
    allowed = frozenset(values)
    return lambda value: value if isinstance(value, str) and value in allowed else _MISSING


def _array(project, maximum):
    def apply(value):
        if not isinstance(value, (list, tuple)):
            return _MISSING
        if len(value) > maximum:
            raise ValueError("Evidence exceeds its declared collection bound")
        result = []
        for item in value:
            projected = project(item)
            if projected is not _MISSING:
                result.append(projected)
        return result

    return apply


def _object(fields):
    order = {key: index for index, key in enumerate(fields)}

    def apply(value):
        if not isinstance(value, dict):
            return _MISSING
        # The allowed keys the value has, in declaration order; a track point holds a few
        # of the many declared point fields.
        present = sorted((key for key in value if key in order), key=order.__getitem__)
        result = {}
        for key in present:
            if value[key] is None:
                result[key] = None
                continue
            projected = fields[key](value[key])
            if projected is not _MISSING:
                result[key] = projected
        return result

    return apply


def _url(value):
    if _text(value, 1200) is _MISSING:
        return _MISSING
    try:
        parsed = urlsplit(value)
        host = parsed.hostname or ""
        if (
            parsed.scheme != "https"
            or not host
            or "." not in host
            or parsed.username
            or parsed.password
            or host.endswith((".local", ".internal", ".ts.net", ".localhost"))
            or re.fullmatch(r"[0-9.]+", host)
            or ":" in host
        ):
            return _MISSING
    except ValueError:
        return _MISSING
    return value


def _identifier(field):
    expression = rules.IDENTIFIERS[field]
    return lambda value: rules.identifier(value, expression) or _MISSING


def _tracked_address(value):
    if not isinstance(value, str) or not re.fullmatch(r"~?[0-9a-fA-F]{6}", value):
        return _MISSING
    return value.lower()


def _flags(value):
    """Preserve unknown blocking flags as a controlled hold, without their text."""
    if not isinstance(value, list):
        return ["unknown_quality_flag"] if value else []
    if len(value) > 64:
        raise ValueError("Too many quality flags")
    known = set(episode_evidence.LIMITATIONS)
    # Confirmation quality flags are generated by telemetry.quality().
    known.update(
        {
            "indirect_source",
            "unknown_source",
            "mixed_sources",
            "low_position_quality",
            "stale_position",
            "position_speed_disagreement",
            "field_source_disagreement",
            "ground_speed_implausible",
            "type_identity_conflict",
            "rated_speed_implausible",
        }
    )
    return sorted(
        {item if isinstance(item, str) and item in known else "unknown_quality_flag" for item in value}
    )


