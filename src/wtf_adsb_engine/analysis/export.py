def finding_key(source, *, source_instance="receiver"):
    """Private legacy identity; published IDs contain only its UUID mapping."""
    evidence = source.get("evidence") or {}
    maneuver = evidence.get("maneuver") or {}
    return json.dumps(
        [
            source_instance,
            str(source["hex"]).lower(),
            source["kind"],
            number(source["first_seen"]),
            number(evidence.get("encounter_start")),
            number(maneuver.get("episode_start")),
            stories.provenance(source, evidence),
        ],
        separators=(",", ":"),
        allow_nan=False,
    )


def finding_id(source, *, source_instance="receiver"):
    return str(
        uuid5(NAMESPACE_URL, "wtf-adsb:finding:" + finding_key(source, source_instance=source_instance))
    )


def project_source(source, *, source_instance="receiver", finding_identifier=None, now=None):
    """Sanctioned migration finding, retaining enough proof for existing policy.

    `now` (default: the current time) is the export time a stale type check is dated
    by when the selection is rebuilt (curation.stale_check).
    """
    if source.get("kind") not in FINDING_KINDS:
        return None
    evidence = EVIDENCE(source.get("evidence"))
    if evidence is _MISSING or not evidence.get("aircraft"):
        raise ValueError("Finding is missing its aircraft evidence")
    address = _tracked_address(source.get("hex"))
    first, last = number(source.get("first_seen")), number(source.get("last_seen"))
    if address is _MISSING or first is None or last is None or first > last:
        raise ValueError("Finding identity or interval is invalid")
    origin = stories.provenance(source, source["evidence"])
    result = {
        "id": finding_identifier or finding_id(source, source_instance=source_instance),
        "hex": address.lower(),
        "kind": source["kind"],
        "category": source["category"]
        if source.get("category") in {"airframes", "performance", "patterns", "oddities", "signals"}
        else "oddities",
        "value": number(source.get("value")),
        "unit": source.get("unit")
        if source.get("unit")
        in {
            "",
            "kn",
            "kt",
            "ft",
            "ft/min",
            "NM",
            "nm",
            "years",
            "coverage days",
            "kn implied",
            "kn difference",
            "minutes",
            "passes",
            "aircraft",
            "seconds",
            "s",
            "loops",
            "turns",
            "reports",
            "degrees",
            "deg/s",
            "Mach",
            "%",
        }
        else "",
        "first_seen": first,
        "last_seen": last,
        "hits": max(0, int(number(source.get("hits")) or 0)),
        "origin": selection.LIVE_ORIGIN
        if origin == "live"
        else "Historical corpus: "
        + {"archive-heatmap": "heatmap", "archive-traces": "traces"}.get(origin, "archive"),
        "verdict": source.get("verdict")
        if source.get("verdict") in {"keep", "routine", "bad_data"}
        else None,
        "evidence": evidence,
    }
    decision = source.get("selection") or selection.assess(result, {}, now=now)
    result["selection"] = {
        key: decision.get(key)
        for key in (
            "version",
            "score",
            "promoted",
            "story_eligible",
            "review_required",
            "publication_hold",
            "verdict",
        )
    }
    result["selection"]["blocking_rules"] = [
        value for value in decision.get("blocking_rules", []) if _token(value) is not _MISSING
    ]
    # Reconstruct reasons from sanitized facts; never forward a saved free-text reason.
    result["selection"]["reasons"] = selection.assess(result, {}, now=now)["reasons"]
    if evidence.get("absorbed_by") or source["kind"] not in stories.STORY_KINDS:
        result["selection"].update(promoted=False, story_eligible=False, review_required=True)
        result["selection"]["blocking_rules"].append(
            "superseded_finding" if evidence.get("absorbed_by") else "unsupported_publication_kind"
        )
    return result


def _point_media(raw):
    altitude, reference = None, None
    for key, label in (
        ("alt_baro", "barometric"),
        ("alt_geom", "geometric"),
        ("archive_alt", "unspecified"),
        ("alt", "unspecified"),
    ):
        altitude = number(raw.get(key))
        if altitude is not None:
            reference = label
            break
    speed = number(raw.get("gs"))
    return {
        "speed": speed if speed is not None and speed >= 0 else None,
        "altitude": altitude,
        "altitude_reference": reference,
    }


def _positioned(points):
    return isinstance(points, list) and any(
        isinstance(p, dict) and number(p.get("lat")) is not None and number(p.get("lon")) is not None
        for p in points
    )


def media_parts(source):
    """The drawn track parts: the first sample list that holds positions, within the
    finding's interval. A TCAS finding's maneuver samples are positionless advisory
    reports, so its context samples supply the map, over the context window around
    the interval (maneuvers.CONTEXT_MARGIN_SECONDS each side)."""
    evidence = source["evidence"]
    key, points = next(
        (
            (key, found)
            for key in ("maneuver_samples", "pattern_samples", "track", "context_samples")
            if _positioned(found := evidence.get(key))
        ),
        (None, []),
    )
    margin = maneuvers.CONTEXT_MARGIN_SECONDS if key == "context_samples" else 0
    window = [
        point
        for point in points
        if (stamp := number(point.get("ts"))) is not None
        and source["first_seen"] - margin <= stamp <= source["last_seen"] + margin
    ]
    return airport_context.parts(window, describe=_point_media)


def _norm_inputs(aircraft, address):
    """(type code, (phase, band), address) a type norm reads, as the legacy autopilot passes them."""
    aircraft = aircraft if isinstance(aircraft, dict) else {}
    return aircraft.get("t"), rules.performance_context(aircraft), address


class _TypeNorms:
    """Per-finding type speed norms (selection.type_norm) for curation.NORM_KINDS findings.

    The sample rows are read once per export, as autopilot.collect reads them, and the
    contexts only when a norm-kind finding needs them. With an identity sidecar, a finding
    keeps the norm of the first export at which its group is quiet and curation.type_hold
    holds it no longer (IdentityStore.type_norm): the legacy pass stages a norm only when
    it selects the finding, so a type check outage freezes no older window.
    """

    def __init__(self, connection, rows, identities, now):
        self.connection, self.rows, self.identities, self.now = connection, rows, identities, now
        self.quiet_before = now - selection.QUIET_SECONDS
        self.contexts = None
        self.indexed, self.norms = {}, {}

    def _index(self, key):
        """One context's entries as selection.type_norm reads them, prepared once per export:
        medians and weights in percentile order, each address's positions in that order, and
        the entries per UTC day, overall and per address."""
        if self.contexts is None:
            self.contexts = selection.norm_contexts(self.connection, self.rows)
        entries = self.contexts.get(key, ())
        by_address = Counter(address for address, _, _ in entries)
        ordered = sorted(
            ((median, 1 / by_address[address], address, encounter) for address, encounter, median in entries),
            key=lambda item: item[:2],
        )
        positions, days, address_days = defaultdict(list), Counter(), defaultdict(Counter)
        for position, (_, _, address, encounter) in enumerate(ordered):
            positions[address].append(position)
            if number(encounter) is not None:
                day = datetime.fromtimestamp(encounter, timezone.utc).date()
                days[day] += 1
                address_days[address][day] += 1
        return {
            "medians": [item[0] for item in ordered],
            "weights": [item[1] for item in ordered],
            "positions": positions,
            "days": days,
            "address_days": address_days,
        }

    @staticmethod
    def _percentile(medians, weights, share):
        """selection._weighted_percentile over entries already in its order: the same total
        (sum) and running sums (accumulate adds in the same order), found by bisection."""
        cumulative = list(accumulate(weights))
        index = bisect_left(cumulative, share * sum(weights) - 1e-9)
        return medians[min(index, len(medians) - 1)]

    def compute(self, typecode, phase_band, address):
        """selection.type_norm(contexts, typecode, phase_band, address), from the prepared index.

        Leaving one address out removes only its entries: every other address keeps its
        weight, so the remaining entries keep their percentile order and sums.
        """
        if not typecode or not phase_band:
            return None
        phase, band = phase_band
        key = (typecode, phase, band)
        if key not in self.indexed:
            self.indexed[key] = self._index(key)
        index = self.indexed[key]
        held = index["positions"].get(address, ())
        # One answer for every address the context does not hold.
        cached = (key, address if held else None)
        if cached not in self.norms:
            medians, weights = index["medians"], index["weights"]
            if held:
                bounds = [-1, *held, len(medians)]
                spans = [slice(low + 1, high) for low, high in zip(bounds, bounds[1:], strict=False)]
                medians = [value for span in spans for value in medians[span]]
                weights = [value for span in spans for value in weights[span]]
            mine = index["address_days"].get(address, {}) if held else {}
            days = sum(1 for day, count in index["days"].items() if count > mine.get(day, 0))
            addresses = len(index["positions"]) - bool(held)
            norm = None
            if addresses >= selection.NORM_MIN_ADDRESSES and days >= selection.CONTEXT_DAYS:
                norm = {
                    "low": round(self._percentile(medians, weights, 0.1) / 5) * 5,
                    "high": round(self._percentile(medians, weights, 0.9) / 5) * 5,
                    "phase": phase,
                    "band_floor_ft": max(selection.SAMPLE_FLOOR_FT, int(band) * 10000),
                    "band_ceiling_ft": (int(band) + 1) * 10000,
                    "addresses": addresses,
                    "days": days,
                    "window_days": selection.NORM_WINDOW_DAYS,
                }
            self.norms[cached] = norm
        norm = self.norms[cached]
        return None if norm is None else dict(norm)

    def __call__(self, finding_id, source, last_seen):
        inputs = _norm_inputs(source["evidence"].get("aircraft"), source["hex"])
        if self.identities is None:
            return self.compute(*inputs)
        settled = last_seen <= self.quiet_before and curation.type_hold(source, now=self.now) is None
        return self.identities.type_norm(finding_id, inputs, settled, lambda: self.compute(*inputs))


def _with_norms(context, norms):
    """The day context, plus type_norms when the group has a norm-kind finding; the shared
    day context itself is never changed."""
    return {**context, "type_norms": norms} if norms else context


def _encounters(connection, now, profiles):
    """The legacy autopilot's encounters, each with the absorbed rows of its encounter.

    Bounds, start and grouping come from the rows selection leaves in
    (include_absorbed=False), as autopilot.collect reads them, so an absorbed
    row never widens the quiet test, the interval or the novelty day. An
    absorbed row joins the encounter of the shape that absorbed it, else that
    of a row it was grouped with; one with neither keeps its own group.
    """
    # The journal rows are read once. The widened grouping runs first, so each row that
    # selection leaves in ends with the selection the narrow grouping gives it.
    options = {
        "ignore_reviews": False,
        "identity_cooldown": False,
        "rows": list(selection._rows(connection, now)),
    }
    widened = selection.encounters(connection, now, profiles, include_absorbed=True, **options)
    groups = selection.encounters(connection, now, profiles, **options)
    order = {event["id"]: index for index, event in enumerate(e for g in widened for e in g["events"])}
    owner = {event["id"]: group for group in groups for event in group["events"]}
    orphans = []
    for wide in widened:
        absorbed = [event for event in wide["events"] if curation.absorbed(event)]
        if not absorbed:
            continue
        kept = next((owner[event["id"]] for event in wide["events"] if event["id"] in owner), None)
        left = []
        for event in absorbed:
            target = owner.get(event["evidence"]["absorbed_by"].get("event_id")) or kept
            (left if target is None else target["events"]).append(event)
        if left:
            first, last = min(e["first_seen"] for e in left), max(e["last_seen"] for e in left)
            orphans.append({**wide, "events": left, "first_seen": first, "last_seen": last})
    for group in groups:
        group["events"].sort(key=lambda event: order[event["id"]])
    return sorted([*groups, *orphans], key=lambda group: order[group["events"][0]["id"]])


def snapshot(database, now, *, source_instance="receiver", identity_path=None):
    """Current observation projection; use snapshot_state for the durable feed."""
    return snapshot_state(database, now, source_instance=source_instance, identity_path=identity_path)[
        "observations"
    ]


def snapshot_state(database, now, *, source_instance="receiver", identity_path=None, health_mode=None):
    """Read a consistent journal view, without changing its data or querying providers.

    Snapshot absence has no withdrawal semantics. A private identity sidecar
    emits witnessed structural supersessions, and retries their replacement
    evidence until the independent core outbox can commit it. When health_mode
    is supplied, analysis health is checked in the same read transaction.
    """
    if not isinstance(source_instance, str) or not source_instance:
        raise ValueError("A persistent source instance is required")
    if number(now) is None:
        raise ValueError("A finite snapshot time is required")
    uri = Path(database).resolve().as_uri() + "?mode=ro"
    identity_context = (
        IdentityStore(identity_path, source_instance) if identity_path is not None else nullcontext(None)
    )
    with identity_context as identities, closing(sqlite3.connect(uri, uri=True)) as connection:
        connection.row_factory = sqlite3.Row
        connection.execute("BEGIN")
        if health_mode is not None:
            journal_watermark(connection, health_mode)
        # The sample rows feed the spotting thresholds and the type norms; they are read once.
        rows = selection.sample_rows(connection)
        groups = _encounters(connection, now, selection.performance_profiles(connection, rows))
        type_norms = _TypeNorms(connection, rows, identities, now)
        novelty = selection.novelty(connection)

        @lru_cache(maxsize=None)
        def day_context(day):
            counts = novelty(day)
            return {
                "novelty": {
                    "coverage_days": counts["coverage_days"],
                    "type_days": {
                        code: count
                        for code, count in sorted(counts["type_days"].items())
                        if rules.identifier(code, rules.IDENTIFIERS["type_code"])
                    },
                },
                "policy_profile": PROFILE,
            }

        results, keys = [], set()
        for group in groups:
            events, norms = [], {}
            for compact in group["events"]:
                if compact["kind"] not in FINDING_KINDS:
                    continue
                row = connection.execute(
                    "SELECT evidence FROM events WHERE id=?", (compact["id"],)
                ).fetchone()
                full = {**compact, "evidence": json.loads(row["evidence"])}
                # Preserve a fresh saved registry check attached by selection._rows.
                if "type_check" in compact["evidence"]:
                    full["evidence"]["type_check"] = compact["evidence"]["type_check"]
                projected = project_source(
                    full,
                    source_instance=source_instance,
                    finding_identifier=identities.finding(full) if identities is not None else None,
                    now=now,
                )
                if projected is not None:
                    events.append(projected)
                    if projected["kind"] in curation.NORM_KINDS:
                        norms[projected["id"]] = type_norms(projected["id"], full, group["last_seen"])
            if not events:
                continue
            start = group.get("start") if group.get("start") is not None else group["first_seen"]
            key = json.dumps(
                [source_instance, events[0]["hex"], start], separators=(",", ":"), allow_nan=False
            )
            if key in keys:
                if identities is None:
                    raise ValueError("Ambiguous legacy encounter identity requires reconciliation")
                key += ":" + events[0]["id"]
            keys.add(key)
            episode_id = str(uuid5(NAMESPACE_URL, "wtf-adsb:episode:" + key))
            day = datetime.fromtimestamp(group["first_seen"], timezone.utc).date().isoformat()
            results.append(
                {
                    "key": key,
                    "observation": {
                        "group": {
                            "id": episode_id,
                            "events": events,
                            "first_seen": group["first_seen"],
                            "last_seen": group["last_seen"],
                            "start": group.get("start"),
                            "registration": rules.identifier(
                                group.get("registration"), rules.IDENTIFIERS["registration"]
                            ),
                        },
                        "context": _with_norms(day_context(day), norms),
                        "media": {
                            "by_finding": {event["id"]: {"parts": media_parts(event)} for event in events}
                        },
                    },
                }
            )
        retractions = []
        if identities is not None:
            assigned = identities.assign_groups(
                [
                    (row["key"], [event["id"] for event in row["observation"]["group"]["events"]])
                    for row in results
                ]
            )
            for row, identifier in zip(results, assigned, strict=True):
                row["key"] = identifier
                row["observation"]["group"]["id"] = identifier
            restored = identities.replacement_rows(results)
            for row in restored:
                observation = row["observation"]
                day = (
                    datetime.fromtimestamp(observation["group"]["first_seen"], timezone.utc)
                    .date()
                    .isoformat()
                )
                # The source rows are gone: a finding keeps the norm its saved payload carries,
                # and a payload saved before type norms existed takes one from its evidence.
                saved = observation["context"].get("type_norms") or {}
                norms = {
                    event["id"]: saved[event["id"]]
                    if event["id"] in saved
                    else type_norms.compute(*_norm_inputs(event["evidence"].get("aircraft"), event["hex"]))
                    for event in observation["group"]["events"]
                    if event["kind"] in curation.NORM_KINDS
                }
                observation["context"] = _with_norms(day_context(day), norms)
            results.extend(restored)
            identities.remember_replacements(results)
            identities.retain_type_norms()
            retractions = identities.retractions()
        return {"observations": results, "retractions": retractions}
